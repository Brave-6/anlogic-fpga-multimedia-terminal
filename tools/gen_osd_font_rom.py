"""Build a packed 16-row one-bit text atlas and explicit 9K ROM wrappers."""
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/user_source/hdl_source/osd'
ASSETS = ROOT / 'assets/osd_bottom_20261008'
DEFS = [
    ('BRIGHT', '亮度', 12, False), ('MODE', '640x480@59.52Hz', 12, False),
    ('RUN', 'FPGA RUN', 12, False), ('HOLD', 'FPGA HOLD', 12, False),
    ('EMERG', '应急模式', 12, False), ('TAG_NORMAL', '园区通知', 12, True),
    ('TAG_EMERG', '应急通报', 12, True),
    ('PAGE1', '01/04', 12, False), ('PAGE2', '02/04', 12, False),
    ('PAGE3', '03/04', 12, False), ('PAGE4', '04/04', 12, False),
    ('TICK_P2', '今日温馨提示：园区供水管道检修将于11月5日进行，请A座、B座单元提前储水。', 14, False),
    ('TICK_P3', '园区科技开放日：FPGA创新设计大赛优秀作品展。11月20日09:00至16:00，展位A12，欢迎莅临参观。', 14, False),
    ('TICK_P4', '应急通报：消防疏散演练进行中。请沿安全通道有序撤离，切勿乘坐电梯。集合点：东广场。', 14, False),
]

def render(text, size, bold=False, height=16):
    font = ImageFont.truetype('C:/Windows/Fonts/msyhbd.ttc' if bold else 'C:/Windows/Fonts/msyh.ttc', size)
    image = Image.new('L', (int(font.getlength(text)+1), height))
    draw = ImageDraw.Draw(image)
    box = draw.textbbox((0,0), text, font=font)
    draw.text((0,(height-box[3]+box[1])//2-box[1]), text, font=font, fill=255)
    return image.point(lambda v: 255 if v >= 96 else 0)

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    words, layout, previews = [], {}, []
    def add(name, text, image, y0=0):
        layout[name] = dict(start=len(words), width=image.width, text=text)
        for x in range(image.width):
            words.append(sum(1<<y for y in range(16) if y+y0<image.height and image.getpixel((x,y+y0))))
    for name,text,size,bold in DEFS:
        image = render(text,size,bold)
        if name.startswith('TICK_'):
            extended = Image.new('L',(image.width+112,16)); extended.paste(image,(0,0)); image=extended
            assert image.width > 546
        add(name,text,image); previews.append((name,image))
    popup=render('亮度',20,True,24)
    add('POP_TOP','亮度',popup); add('POP_BOTTOM','亮度',popup,16)
    banks=(len(words)+511)//512
    assert banks<=16
    padded=words+[0]*(banks*512-len(words))
    (OUT/'osd_text.mem').write_text(''.join(f'{v:04X}\n' for v in padded),encoding='ascii')
    for bank in range(banks):
        (OUT/f'osd_text_bank{bank:02d}.dat').write_text(''.join(f'{v:016b}\n' for v in padded[bank*512:(bank+1)*512]),encoding='ascii')
        lines=['WIDTH=16;','DEPTH=512;','ADDRESS_RADIX=UNS;','DATA_RADIX=HEX;','CONTENT BEGIN']
        lines += [f'{i} : {padded[bank*512+i]:04X};' for i in range(512)]+['END;']
        (OUT/f'osd_text_bank{bank:02d}.mif').write_text('\n'.join(lines)+'\n',encoding='ascii')
    params=['// Generated by tools/gen_osd_font_rom.py.']
    for name,item in layout.items():
        params += [f"localparam [12:0] {name}_START = 13'd{item['start']};",
                   f"localparam [12:0] {name}_WIDTH = 13'd{item['width']};"]
    (OUT/'osd_layout.vh').write_text('\n'.join(params)+'\n',encoding='ascii')
    lines=['// Generated synchronous text atlas, 9K BRAM only.',
           'module osd_bitmap_rom(input wire I_clk, input wire [12:0] I_addr, output reg [15:0] O_data);',
           '`ifdef OSD_SIM',f'reg [15:0] mem [0:{len(padded)-1}];',
           'initial $readmemh("osd/osd_text.mem",mem);',
           'always @(posedge I_clk) O_data <= mem[I_addr];','`else',
           'reg [3:0] bank_d;','always @(posedge I_clk) bank_d <= I_addr[12:9];']
    for bank in range(banks):
        lines += [f'''wire [15:0] q{bank};
EG_LOGIC_BRAM #(.DATA_WIDTH_A(16), .ADDR_WIDTH_A(9), .DATA_DEPTH_A(512),
 .DATA_WIDTH_B(16), .ADDR_WIDTH_B(9), .DATA_DEPTH_B(512), .MODE("SP"),
 .REGMODE_A("NOREG"), .IMPLEMENT("9K"), .DEBUGGABLE("NO"), .PACKABLE("NO"),
 .INIT_FILE("osd_text_bank{bank:02d}.mif"), .FILL_ALL("NONE")) bank{bank} (
 .dia(16'd0), .dib(16'd0), .addra(I_addr[8:0]), .addrb(9'd0),
 .cea(1'b1), .ceb(1'b0), .ocea(1'b0), .oceb(1'b0), .clka(I_clk), .clkb(1'b0),
 .wea(1'b0), .web(1'b0), .bea(1'b0), .beb(1'b0), .rsta(1'b0), .rstb(1'b0), .doa(q{bank}), .dob());''']
    lines += ['always @* begin','case (bank_d)']
    lines += [f"4'd{bank}: O_data = q{bank};" for bank in range(banks)]
    lines += ["default: O_data = 16'd0;",'endcase','end','`endif','endmodule']
    (OUT/'osd_bitmap_rom.v').write_text('\n'.join(lines)+'\n',encoding='ascii')
    (ASSETS/'layout.json').write_text(json.dumps(dict(words=len(words),banks_9k=banks,layout=layout),ensure_ascii=False,indent=2),encoding='utf-8')
    sheet=Image.new('RGB',(1500,len(previews)*26),'white')
    for row,(name,image) in enumerate(previews):
        ImageDraw.Draw(sheet).text((2,row*26),name,fill='black')
        sheet.paste(Image.merge('RGB',(image,image,image)),(150,row*26))
    sheet.save(ASSETS/'text_atlas_preview.png')
    print(f'Text atlas: {len(words)} columns in {banks} 9K BRAM banks; no 32K BRAM.')

if __name__=='__main__': main()
